def add_fig(a, b, **kw):
    return lambda t: column_arith(t, a, b, "+", **kw)


def sub_fig(a, b, **kw):
    return lambda t: column_arith(t, a, b, "-", **kw)


def blank_add(a, b):
    return lambda t: column_arith(t, a, b, "+", show_answer=False, size=15)


def blank_sub(a, b):
    return lambda t: column_arith(t, a, b, "-", show_answer=False, size=15)


